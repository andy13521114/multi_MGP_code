fprintf('Tolerance             = %.1e\n',TOL);


%% ================================================================
% 5. Loop over cases
% ================================================================

for icase = 1:numel(cases)

    cfg = cases(icase);

    fprintf('\n');
    fprintf('------------------------------------------------------------\n');
    fprintf('CASE %02d / %02d : %s\n', ...
        icase,numel(cases),cfg.name);

    fprintf( ...
        'M=%d, nh=%d, nv=%d, miss=%.2f, Cs=%s\n', ...
        cfg.M, ...
        cfg.nh, ...
        cfg.nv, ...
        cfg.missing_rate, ...
        cfg.cs_mode);


    %% ------------------------------------------------------------
    % Coordinates
    % -------------------------------------------------------------

    M  = cfg.M;
    nh = cfg.nh;
    nv = cfg.nv;

    x = linspace(0,12,nh)';

    x = x ...
        + 0.10*sin((1:nh)');

    y = 0.8*cos( ...
        (1:nh)'*0.73);

    z = linspace(1.5,5.0,nv)';


    %% ------------------------------------------------------------
    % Trend bases
    % -------------------------------------------------------------

    xc = (x-mean(x))/std(x);
    yc = (y-mean(y))/std(y);

    Hraw = [ ...
        ones(nh,1), ...
        xc, ...
        yc];

    phih = orth(Hraw);


    zc = (z-mean(z))/std(z);

    Zraw = [ ...
        ones(nv,1), ...
        zc, ...
        zc.^2];

    phiz = orth(Zraw);


    Y.phih = phih;
    Y.phiz = phiz;

    mh = size(phih,2);
    mz = size(phiz,2);


    %% ------------------------------------------------------------
    % Cs
    % -------------------------------------------------------------

    Cs = build_Cs( ...
        M, ...
        cfg.cs_mode);

    eigCs = eig(Cs);

    fprintf( ...
        'Cs min/max eig = %.3e / %.3e\n', ...
        min(eigCs), ...
        max(eigCs));


    %% ------------------------------------------------------------
    % Parameter eigenbasis
    % -------------------------------------------------------------

    [phi_t_Cs,omega_t_Cs] = eig(Cs);

    eigvals = diag(omega_t_Cs);

    [~,idx] = sort( ...
        eigvals, ...
        'descend');

    phi_t_Cs = ...
        phi_t_Cs(:,idx);


    %% ------------------------------------------------------------
    % alpha
    % -------------------------------------------------------------

    nw = M*mh*mz;

    alpha = exp(linspace( ...
        log(cfg.alpha_min), ...
        log(cfg.alpha_max), ...
        nw))';

    O = diag(1./alpha);


    %% ------------------------------------------------------------
    % Rv
    % -------------------------------------------------------------

    disz = abs(z'-z);

    R_v = Matern_R( ...
        cfg.nu_v, ...
        cfg.sof_v, ...
        disz);

    R_v(isnan(R_v)) = 1;

    R_v = R_v ...
        + 1e-6*eye(nv);


    %% ------------------------------------------------------------
    % Rh
    % -------------------------------------------------------------

    disx = abs(x'-x);
    disy = abs(y'-y);

    dish = sqrt( ...
        disx.^2 ...
        + disy.^2);

    R_h = Matern_R( ...
        cfg.nu_h, ...
        cfg.sof_h, ...
        dish);

    R_h(isnan(R_h)) = 1;

    R_h = R_h ...
        + 1e-6*eye(nh);


    %% ------------------------------------------------------------
    % Exact full covariance
    % -------------------------------------------------------------

    Phi = kron( ...
        phi_t_Cs, ...
        kron(phih,phiz));

    S_trend = ...
        Phi*O*Phi';

    S_res = cfg.bhp * kron( ...
        Cs, ...
        kron(R_h,R_v));

    S = S_trend + S_res;

    S = (S+S')/2;

    LS = chol(S,'lower');


    %% ------------------------------------------------------------
    % Pattern list
    % -------------------------------------------------------------

    pattern_list = [ ...
        repmat({'random'},1,N_RANDOM_PATTERN), ...
        forced_patterns];


    case_fast_diff = [];
    case_factor_diff = [];

    case_fail = 0;


    %% ============================================================
    % Individual tests
    % =============================================================

    for itest = 1:numel(pattern_list)

        total_test = total_test + 1;

        pattern_type = ...
            pattern_list{itest};


        %% --------------------------------------------------------
        % Generate NEW Gaussian sample for every test
        % ---------------------------------------------------------

        y_full = LS * ...
            randn(size(S,1),1);

        data_full = reshape( ...
            y_full, ...
            nv, ...
            nh*M);


        %% --------------------------------------------------------
        % Missing pattern
        % ---------------------------------------------------------

        missing = make_missing_pattern( ...
            nv, ...
            nh, ...
            M, ...
            cfg.missing_rate, ...
            pattern_type);


        data = data_full;

        data(missing) = NaN;

        nan_ind = isnan(data);


        try

            %% ====================================================
            % Exact direct likelihood
            % =====================================================

            obs_ind = ...
                ~nan_ind(:);

            data_vec = ...
                data(:);

            y_obs = ...
                data_vec(obs_ind);

            S_oo = ...
                S(obs_ind,obs_ind);

            S_oo = ...
                (S_oo+S_oo')/2;

            L = chol( ...
                S_oo, ...
                'lower');

            v = L\y_obs;

            logL_direct = ...
                -0.5*numel(y_obs)*log(2*pi) ...
                -sum(log(diag(L))) ...
                -0.5*(v'*v);


            %% ====================================================
            % Exact conditional factorization
            % =====================================================

            nan_r_n = ...
                sum(nan_ind,2);

            z_minus = ...
                (nan_r_n == 0);

            z_plus = ...
                (nan_r_n > 0);


            minus = false( ...
                nv, ...
                nh*M);

            minus(z_minus,:) = true;

            idx_minus = ...
                minus(:);


            plus_o = false( ...
                nv, ...
                nh*M);

            plus_o(z_plus,:) = ...
                ~nan_ind(z_plus,:);

            idx_plus_o = ...
                plus_o(:);


            y_minus = ...
                data_vec(idx_minus);

            y_plus_o = ...
                data_vec(idx_plus_o);


            % p(y_minus)
            S_mm = ...
                S(idx_minus,idx_minus);

            S_mm = ...
                (S_mm+S_mm')/2;

            Lm = chol( ...
                S_mm, ...
                'lower');

            vm = Lm\y_minus;

            logL_minus = ...
                -0.5*numel(y_minus)*log(2*pi) ...
                -sum(log(diag(Lm))) ...
                -0.5*(vm'*vm);


            % p(y_plus_o | y_minus)
            S_pm = ...
                S(idx_plus_o,idx_minus);

            S_pp = ...
                S(idx_plus_o,idx_plus_o);


            tmp = Lm\y_minus;
            tmp = Lm'\tmp;

            mu_cond = ...
                S_pm*tmp;


            tmp = Lm\S_pm';
            tmp = Lm'\tmp;

            S_cond = ...
                S_pp ...
                - S_pm*tmp;

            S_cond = ...
                (S_cond+S_cond')/2;


            Lc = chol( ...
                S_cond, ...
                'lower');

            vc = Lc\( ...
                y_plus_o ...
                - mu_cond);

            logL_plus = ...
                -0.5*numel(y_plus_o)*log(2*pi) ...
                -sum(log(diag(Lc))) ...
                -0.5*(vc'*vc);

            logL_factor = ...
                logL_minus ...
                + logL_plus;


            %% ====================================================
            % Fast likelihood
            % =====================================================

            logL_fast = log_like_Step2c( ...
                data, ...
                nan_ind, ...
                x, ...
                y, ...
                z, ...
                cfg.sof_v, ...
                cfg.sof_h, ...
                cfg.nu_v, ...
                cfg.nu_h, ...
                cfg.bhp, ...
                alpha, ...
                Y, ...
                Cs);


            %% ====================================================
            % Difference
            % =====================================================

            diff_factor = ...
                logL_factor ...
                - logL_direct;

            diff_fast = ...
                logL_fast ...
                - logL_direct;


            case_factor_diff(end+1,1) = ...
                diff_factor;

            case_fast_diff(end+1,1) = ...
                diff_fast;


            all_factor_diff(end+1,1) = ...
                diff_factor;

            all_fast_diff(end+1,1) = ...
                diff_fast;

            all_case_id(end+1,1) = ...
                icase;

            all_pattern{end+1,1} = ...
                pattern_type;

            all_test_id(end+1,1) = ...
                itest;


            %% ----------------------------------------------------
            % Failure report
            % -----------------------------------------------------

            if abs(diff_fast) >= TOL

                case_fail = ...
                    case_fail + 1;

                failure_count = ...
                    failure_count + 1;


                if failure_count <= MAX_FAILURE_PRINT

                    fprintf('\n');
                    fprintf('*** FAST FAILURE %d ***\n', ...
                        failure_count);

                    fprintf( ...
                        'Case       = %s\n', ...
                        cfg.name);

                    fprintf( ...
                        'Pattern    = %s\n', ...
                        pattern_type);

                    fprintf( ...
                        'M/nh/nv    = %d / %d / %d\n', ...
                        M,nh,nv);

                    fprintf( ...
                        'N observed = %d\n', ...
                        numel(y_obs));

                    fprintf( ...
                        'N minus    = %d\n', ...
                        numel(y_minus));

                    fprintf( ...
                        'N plus     = %d\n', ...
                        numel(y_plus_o));

                    fprintf( ...
                        'Direct     = %.15f\n', ...
                        logL_direct);

                    fprintf( ...
                        'Factor     = %.15f\n', ...
                        logL_factor);

                    fprintf( ...
                        'Fast       = %.15f\n', ...
                        logL_fast);

                    fprintf( ...
                        'Factor diff= %.6e\n', ...
                        diff_factor);

                    fprintf( ...
                        'Fast diff  = %.6e\n', ...
                        diff_fast);

                    fprintf( ...
                        'Missing count/depth:\n');

                    disp( ...
                        sum(nan_ind,2)');

                end

            end


        catch ME

            case_fail = ...
                case_fail + 1;

            failure_count = ...
                failure_count + 1;

            fprintf('\n');
            fprintf('*** MATLAB ERROR ***\n');

            fprintf( ...
                'Case    = %s\n', ...
                cfg.name);

            fprintf( ...
                'Pattern = %s\n', ...
                pattern_type);

            fprintf( ...
                'Error   = %s\n', ...
                ME.message);

            all_factor_diff(end+1,1) = NaN;
            all_fast_diff(end+1,1)   = Inf;

            all_case_id(end+1,1) = ...
                icase;

            all_pattern{end+1,1} = ...
                pattern_type;

            all_test_id(end+1,1) = ...
                itest;

        end

    end


    %% ============================================================
    % Case summary
    % =============================================================

    summary_result(icase).Case = ...
        cfg.name;

    summary_result(icase).M = ...
        M;

    summary_result(icase).nh = ...
        nh;

    summary_result(icase).nv = ...
        nv;

    summary_result(icase).MissingRate = ...
        cfg.missing_rate;

    summary_result(icase).CsMode = ...
        cfg.cs_mode;

    summary_result(icase).MaxFactorDiff = ...
        max(abs(case_factor_diff),[],'omitnan');

    summary_result(icase).MaxFastDiff = ...
        max(abs(case_fast_diff),[],'omitnan');

    summary_result(icase).MeanFastDiff = ...
        mean(abs(case_fast_diff),'omitnan');

    summary_result(icase).NFail = ...
        case_fail;


    fprintf( ...
        'max factor diff = %.3e\n', ...
        summary_result(icase).MaxFactorDiff);

    fprintf( ...
        'max fast diff   = %.3e\n', ...
        summary_result(icase).MaxFastDiff);

    fprintf( ...
        'failures        = %d\n', ...
        case_fail);

end


