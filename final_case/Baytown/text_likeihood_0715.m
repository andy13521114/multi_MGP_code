function cfg = make_case( ...
    name, ...
    M,nh,nv, ...
    missing_rate, ...
    sof_v,sof_h, ...
    nu_v,nu_h, ...
    bhp, ...
    cs_mode, ...
    alpha_min,alpha_max)

cfg.name = name;

cfg.M  = M;
cfg.nh = nh;
cfg.nv = nv;

cfg.missing_rate = ...
    missing_rate;

cfg.sof_v = sof_v;
cfg.sof_h = sof_h;

cfg.nu_v = nu_v;
cfg.nu_h = nu_h;

cfg.bhp = bhp;

cfg.cs_mode = ...
    cs_mode;

cfg.alpha_min = ...
    alpha_min;

cfg.alpha_max = ...
    alpha_max;

end


%% ================================================================

function Cs = build_Cs(M,mode)

switch lower(mode)

    case 'weak'

        rho = 0.20;

        R = (1-rho)*eye(M) ...
            + rho*ones(M);


    case 'strong'

        rho = 0.90;

        R = (1-rho)*eye(M) ...
            + rho*ones(M);


    case 'near'

        rho = 0.98;

        R = (1-rho)*eye(M) ...
            + rho*ones(M);


    case 'negative'

        rho = -0.65;

        first_col = ...
            rho.^(0:M-1);

        R = toeplitz(first_col);


    case 'random'

        A = randn(M);

        R = A*A' ...
            + 0.30*eye(M);

        d = sqrt(diag(R));

        R = R./(d*d');


    otherwise

        error( ...
            'Unknown Cs mode: %s', ...
            mode);

end


% Unequal marginal variances
scales = linspace( ...
    0.8, ...
    1.4, ...
    M)';

D = diag(scales);

Cs = D*R*D;

Cs = (Cs+Cs')/2;


% SPD check
if min(eig(Cs)) <= 0

    error( ...
        'Generated Cs is not SPD.');

end

end


%% ================================================================

function missing = make_missing_pattern( ...
    nv,nh,M,missing_rate,pattern_type)

ncol = nh*M;

missing = ...
    rand(nv,ncol) < missing_rate;


switch lower(pattern_type)

    %% ------------------------------------------------------------
    case 'random'
        % Use default random pattern


    %% ------------------------------------------------------------
    case 'exact_nh_missing'

        r = min(5,nv);

        missing(r,:) = false;

        idx = randperm( ...
            ncol, ...
            nh);

        missing(r,idx) = true;


    %% ------------------------------------------------------------
    case 'full_depth_missing'

        r = min(5,nv);

        missing(r,:) = true;


    %% ------------------------------------------------------------
    case 'parameter_block'

        p = M;

        cols = ...
            (p-1)*nh + (1:nh);

        row_end = max( ...
            3, ...
            floor(0.75*nv));

        rows = 3:row_end;

        missing(rows,cols) = true;


    %% ------------------------------------------------------------
    case 'hole_block'

        h = ceil(nh/2);

        cols = ...
            h + (0:M-1)*nh;

        rows = 3:nv;

        missing(rows,cols) = true;


    %% ------------------------------------------------------------
    case 'heavy_random'

        missing = ...
            rand(nv,ncol) < 0.55;


    %% ------------------------------------------------------------
    case 'checkerboard'

        missing = ...
            false(nv,ncol);

        for iz = 3:nv

            for ic = 1:ncol

                if mod(iz+ic,3) == 0

                    missing(iz,ic) = true;

                end

            end

        end


    otherwise

        error( ...
            'Unknown missing pattern: %s', ...
            pattern_type);

end


%% ---------------------------------------------------------------
% Always retain complete depth rows
% ---------------------------------------------------------------

n_complete = min(2,nv);

missing(1:n_complete,:) = false;


%% ---------------------------------------------------------------
% Ensure at least one PARTIAL non-lattice depth
% ---------------------------------------------------------------

missing_count = ...
    sum(missing,2);

partial_depth = ...
    missing_count > 0 ...
    & missing_count < ncol;

if ~any(partial_depth)

    r = min(3,nv);

    missing(r,1) = true;

end

end